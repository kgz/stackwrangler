#!/usr/bin/env bash
# Dual-role aws-redirect: dnsmasq (AWS → self, else upstream) + TLS edge → LocalEmu.
set -euo pipefail

CERT_DIR="${AWS_REDIRECT_CERT_DIR:-/certs}"
DNS_LOG="${AWS_REDIRECT_DNS_LOG:-/var/log/aws-redirect-dnsmasq.log}"
DNS_CONF="${AWS_REDIRECT_DNS_CONF:-/tmp/aws-redirect-dnsmasq.conf}"
TLS_PID_FILE="${AWS_REDIRECT_TLS_PID:-/var/run/aws-redirect-tls.pid}"
LOCALEMU_URL="${LOCALEMU_URL:-http://localstack:4566}"
UPSTREAM_DNS="${AWS_REDIRECT_UPSTREAM_DNS:-}"

mkdir -p "$CERT_DIR" /var/run

if [[ ! -f "$CERT_DIR/ca.key" || ! -f "$CERT_DIR/ca.crt" ]]; then
	echo "aws-redirect: generating local CA under ${CERT_DIR}"
	openssl req -x509 -newkey rsa:2048 -nodes \
		-keyout "$CERT_DIR/ca.key" \
		-out "$CERT_DIR/ca.crt" \
		-days 3650 \
		-subj "/CN=awsbox AWS redirect CA/O=awsbox/OU=aws-redirect"
	chmod 644 "$CERT_DIR/ca.crt"
	chmod 600 "$CERT_DIR/ca.key"
fi
cp -f "$CERT_DIR/ca.crt" "$CERT_DIR/ca.pem" 2>/dev/null || true

# Container address clients should dial for AWS hostnames (fail-closed: never real AWS).
PROXY_IP="$(hostname -i | awk '{print $1}')"
if [[ -z "$PROXY_IP" || "$PROXY_IP" == "127.0.0.1" ]]; then
	PROXY_IP="$(ip -4 -o addr show scope global | awk '{print $4}' | cut -d/ -f1 | head -1)"
fi
[[ -n "$PROXY_IP" ]] || {
	echo "aws-redirect: could not determine proxy IP" >&2
	exit 1
}
echo "aws-redirect: proxy IP ${PROXY_IP} → ${LOCALEMU_URL}"

if [[ -z "$UPSTREAM_DNS" ]]; then
	# Docker embedded DNS before we overwrite resolv.conf usage in dnsmasq.
	UPSTREAM_DNS="$(awk '/^nameserver/ {print $2; exit}' /etc/resolv.conf)"
fi
[[ -n "$UPSTREAM_DNS" ]] || UPSTREAM_DNS="1.1.1.1"

cat >"$DNS_CONF" <<EOF
# Generated by aws-endpoint-redirect entrypoint — do not edit.
user=root
listen-address=0.0.0.0
bind-interfaces
no-resolv
no-hosts
log-queries
log-facility=${DNS_LOG}
# Non-AWS → upstream (Serverless licence host, npm, etc.)
server=${UPSTREAM_DNS}
# Never forward AWS suffixes upstream (blocks A and AAAA to public AWS).
# address=/…/<IPv4> alone still lets AAAA fall through to real dualstack.
local=/amazonaws.com/
local=/amazonaws.com.cn/
local=/api.aws/
local=/aws.amazon.com/
# IPv4 A → this TLS edge (AAAA under local= → NXDOMAIN / no public addrs).
address=/amazonaws.com/${PROXY_IP}
address=/amazonaws.com.cn/${PROXY_IP}
address=/api.aws/${PROXY_IP}
address=/aws.amazon.com/${PROXY_IP}
EOF

: >"$DNS_LOG"
dnsmasq -C "$DNS_CONF" --pid-file=/var/run/aws-redirect-dnsmasq.pid

export AWS_REDIRECT_CERT_DIR="$CERT_DIR"
export AWS_REDIRECT_TLS_PID="$TLS_PID_FILE"
export LOCALEMU_URL

python3 -u /opt/aws-redirect/tls_proxy.py &
TLS_PID=$!
echo "$TLS_PID" >"$TLS_PID_FILE"

cleanup() {
	if [[ -f "$TLS_PID_FILE" ]]; then
		kill "$(cat "$TLS_PID_FILE")" 2>/dev/null || true
	fi
	kill "$TLS_PID" 2>/dev/null || true
	if [[ -f /var/run/aws-redirect-dnsmasq.pid ]]; then
		kill "$(cat /var/run/aws-redirect-dnsmasq.pid)" 2>/dev/null || true
	fi
}
trap cleanup EXIT

ready=0
for _ in $(seq 1 60); do
	ans="$(dig +short +time=1 +tries=1 @"${PROXY_IP}" sts.amazonaws.com A 2>/dev/null | head -1 || true)"
	if [[ "$ans" == "$PROXY_IP" ]] && kill -0 "$TLS_PID" 2>/dev/null; then
		if python3 - <<'PY'
import socket, ssl, sys
ctx = ssl.create_default_context()
ctx.check_hostname = False
ctx.verify_mode = ssl.CERT_NONE
try:
    with socket.create_connection(("127.0.0.1", 443), timeout=2) as raw:
        with ctx.wrap_socket(raw, server_hostname="sts.us-east-1.amazonaws.com") as s:
            s.sendall(
                b"HEAD / HTTP/1.1\r\n"
                b"Host: sts.us-east-1.amazonaws.com\r\n"
                b"Connection: close\r\n\r\n"
            )
            s.recv(64)
    sys.exit(0)
except Exception as e:
    print(e, file=sys.stderr)
    sys.exit(1)
PY
		then
			echo "aws-redirect: ready (dns+tls)"
			ready=1
			break
		fi
	fi
	if ! kill -0 "$TLS_PID" 2>/dev/null; then
		echo "aws-redirect: TLS proxy exited early" >&2
		exit 1
	fi
	sleep 0.5
done
[[ "$ready" == "1" ]] || {
	echo "aws-redirect: timed out waiting for dns+tls" >&2
	exit 1
}

# Stay up while dnsmasq runs. TLS may be killed for negative smoke (DNS stays).
DNS_PID="$(cat /var/run/aws-redirect-dnsmasq.pid)"
while kill -0 "$DNS_PID" 2>/dev/null; do
	sleep 2
done
echo "aws-redirect: dnsmasq exited" >&2
exit 1
